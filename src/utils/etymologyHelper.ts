export function getEtymologyFallback(word: string, topic?: string): string {
  if (!word) return "Derived from classical Greek or Latin scientific root terms.";
  const cleanWord = word.trim().toLowerCase().replace(/[^a-z]/g, "");

  if (COMMON_ETYMOLOGIES[cleanWord]) {
    return COMMON_ETYMOLOGIES[cleanWord];
  }

  // Prefix/suffix-based smart derivation heuristics
  if (cleanWord.startsWith("micro")) {
    return "From Greek 'mikros' (small) combined with classical scientific roots.";
  }
  if (cleanWord.startsWith("macro")) {
    return "From Greek 'makros' (large/long) combined with classical scientific roots.";
  }
  if (cleanWord.startsWith("bio")) {
    return "From Greek 'bios' (life or living organisms).";
  }
  if (cleanWord.startsWith("photo")) {
    return "From Greek 'phos' / 'photo-' (light).";
  }
  if (cleanWord.startsWith("hydro")) {
    return "From Greek 'hydor' (water).";
  }
  if (cleanWord.startsWith("geo")) {
    return "From Greek 'ge' (earth or land).";
  }
  if (cleanWord.startsWith("thermo")) {
    return "From Greek 'therme' (heat or temperature).";
  }
  if (cleanWord.startsWith("chrono")) {
    return "From Greek 'chronos' (time).";
  }
  if (cleanWord.endsWith("ology") || cleanWord.endsWith("logy")) {
    return "From Greek 'logos' (study, discourse, or branch of knowledge).";
  }
  if (cleanWord.endsWith("ase")) {
    return "Derived using the standard biochemical suffix '-ase' for enzymes.";
  }
  if (cleanWord.endsWith("oid")) {
    return "From Greek '-oeides' (having the form or resemblance of).";
  }
  if (cleanWord.endsWith("synthesis")) {
    return "From Greek 'syn' (together) + 'thesis' (placing or arrangement).";
  }

  if (topic) {
    return `Derived from classical Greek/Latin root terminology in ${topic}.`;
  }

  return "Derived from classical Greek and Latin scientific root terms.";
}
